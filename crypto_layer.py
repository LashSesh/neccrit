"""crypto_layer.py - Sichere Verschlüsselungsschicht (AES-256-GCM)."""
from __future__ import annotations

import hashlib
import os

from cryptography.hazmat.primitives.kdf.scrypt import Scrypt
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

SCRYPT_N = 2 ** 15
SCRYPT_R = 8
SCRYPT_P = 1
SCRYPT_LEN = 32
SALT_SIZE = 16
NONCE_SIZE = 12
HANDSHAKE_LABEL = b"neccrit-handshake-psk"


def _zeroize(buffer: bytearray) -> None:
    for i in range(len(buffer)):
        buffer[i] = 0


def derive_key(password: str, salt: bytes) -> bytes:
    """Derive an AES-256 key using scrypt with the provided salt."""
    if not isinstance(password, str):
        raise TypeError("password must be a string")
    if not isinstance(salt, (bytes, bytearray)):
        raise TypeError("salt must be bytes")
    if len(salt) != SALT_SIZE:
        raise ValueError(f"salt must be {SALT_SIZE} bytes long")
    kdf = Scrypt(salt=salt, length=SCRYPT_LEN, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P)
    return kdf.derive(password.encode("utf-8"))


def derive_handshake_psk(password: str) -> bytes:
    """Derive a deterministic PSK used to salt the HKDF during handshakes."""
    if not isinstance(password, str):
        raise TypeError("password must be a string")
    digest = hashlib.sha256(password.encode("utf-8") + HANDSHAKE_LABEL).digest()
    salt = digest[:SALT_SIZE]
    kdf = Scrypt(salt=salt, length=SCRYPT_LEN, n=SCRYPT_N, r=SCRYPT_R, p=SCRYPT_P)
    return kdf.derive(password.encode("utf-8"))


def encrypt_bytes(data: bytes, password: str) -> bytes:
    """Encrypt *data* with a password using AES-256-GCM and prepend salt+nonce."""
    if not isinstance(password, str):
        raise TypeError("password must be a string")
    salt = os.urandom(SALT_SIZE)
    key_material = bytearray(derive_key(password, salt))
    try:
        aesgcm = AESGCM(bytes(key_material))
        nonce = os.urandom(NONCE_SIZE)
        ciphertext = aesgcm.encrypt(nonce, data, None)
    finally:
        _zeroize(key_material)
    return salt + nonce + ciphertext


def decrypt_bytes(token: bytes, password: str) -> bytes:
    """Decrypt *token* generated by :func:`encrypt_bytes`."""
    if not isinstance(password, str):
        raise TypeError("password must be a string")
    header_length = SALT_SIZE + NONCE_SIZE
    if len(token) <= header_length:
        raise ValueError("Ciphertext is too short to contain salt, nonce, and data")
    salt = token[:SALT_SIZE]
    nonce = token[SALT_SIZE:header_length]
    ciphertext = token[header_length:]
    key_material = bytearray(derive_key(password, salt))
    try:
        aesgcm = AESGCM(bytes(key_material))
        plaintext = aesgcm.decrypt(nonce, ciphertext, None)
    finally:
        _zeroize(key_material)
    return plaintext
